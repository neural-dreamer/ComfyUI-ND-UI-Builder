# Bench 70: the Resolution widget in megapixels (the property «mp»): off by default, the field, ratio buttons aim at the area, arrows, typing, limits.
from lib import *
p, br, pg, errs = start()
J = lambda s, a=None: pg.evaluate(s, a) if a is not None else pg.evaluate(s)
setup(pg)
J("""async () => { const m = await import('/scripts/app.js'); const a = m.app; const LG = window.LiteGraph; a.graph.clear(); window.__app = a;
  const r = LG.createNode('NDResolution'); r.pos=[40,300]; a.graph.add(r); r.properties.nd_ui_src={uid:'sr',tag:'rs'}; }""")
SRC = [{"uid": "sr", "tag": "rs", "class": "NDResolution", "title": "ND Resolution"}]
def use(props, wait=900):
    ui = {"sources": SRC, "pages": [{"id": "p1", "name": "Main"}], "theme": {"id": "midnight"},
          "widgets": [{"id": "c", "type": "resolution", "page": "p1", "x": 20, "y": 20, "w": 440, "h": 260, "z": 1, "slots": {"width": {"src": "sr", "kind": "widget", "name": "width"}, "height": {"src": "sr", "kind": "widget", "name": "height"}}, "props": props}]}
    J("(m) => window.ndUi.host().save(JSON.parse(m))", json.dumps(ui)); pg.wait_for_timeout(wait)
size = lambda: J("""async()=>{const S=await import('/extensions/ComfyUI-NeuralDreamer-UI/ndui/sources.js'); const n=window.__app.graph._nodes.find(n=>n.type==='NDResolution'); return [S.readParam(S.paramByName(n,'width')), S.readParam(S.paramByName(n,'height'))]}""")
mpv = lambda: J("window.ndUi.host().ui.widgets[0].props.mpValue")
vis = lambda sel: J("(s)=>{const e=document.querySelector('.ndk-uimode '+s); return !!e && getComputedStyle(e).display!=='none'}", sel)
J("window.ndUi.enter()"); pg.wait_for_timeout(500)
use({})
check("off by default: no MP field", not vis(".ndk-res-mp"))
check("off by default: the family chip stays", vis(".ndk-res-opts .ndk-chip"))
w0, h0 = size()
pg.click(".ndk-uimode .ndk-res-ratios .ndk-chip[data-r='1:1']"); pg.wait_for_timeout(300)
w, h = size()
check("with MP off the 1:1 button still aims at the size of the family", w == h and abs(w * h - 1048576) / 1048576 < 0.1, str((w, h)))
use({"mp": True, "mpValue": 1})
check("on: the MP field appears", vis(".ndk-res-mp"))
check("on: the family chip is hidden", not J("[...document.querySelectorAll('.ndk-uimode .ndk-res-opts > .ndk-chip')].some(c=>c.textContent.includes('·') && getComputedStyle(c).display!=='none')"))
check("the field shows the value", J("document.querySelector('.ndk-uimode .ndk-res-mp input').value") == "1")
pg.click(".ndk-uimode .ndk-res-ratios .ndk-chip[data-r='1:1']"); pg.wait_for_timeout(300)
w, h = size()
check("1 MP at 1:1 gives about 1024×1024", w == h and abs(w * h - 1e6) / 1e6 < 0.07, str((w, h)))
J("(()=>{const u=JSON.parse(JSON.stringify(window.ndUi.host().ui)); u.widgets[0].props.mpValue=2; window.ndUi.host().save(u)})()"); pg.wait_for_timeout(700)
pg.click(".ndk-uimode .ndk-res-ratios .ndk-chip[data-r='16:9']"); pg.wait_for_timeout(300)
w, h = size()
check("2 MP at 16:9: the area is about 2 MP", abs(w * h - 2e6) / 2e6 < 0.07, str((w, h)))
check("2 MP at 16:9: the ratio is 16:9", abs(max(w, h) / min(w, h) - 16 / 9) < 0.1, str((w, h)))
b = ".ndk-uimode .ndk-res-mp .ndk-iconbtn"
pg.click(b + ":first-of-type"); pg.wait_for_timeout(300)
check("◀ takes 0.1", abs(mpv() - 1.9) < 1e-6, str(mpv()))
pg.click(b + ":last-of-type", modifiers=["Shift"]); pg.wait_for_timeout(300)
check("Shift + ▶ adds 0.5", abs(mpv() - 2.4) < 1e-6, str(mpv()))
w, h = size()
check("the arrows resize and keep the shape", abs(w * h - 2.4e6) / 2.4e6 < 0.07 and abs(max(w, h) / min(w, h) - 16 / 9) < 0.1, str((w, h)))
pg.fill(".ndk-uimode .ndk-res-mp input", "3,5"); pg.keyboard.press("Enter"); pg.wait_for_timeout(400)
w, h = size()
check("typing 3,5 (comma) sets 3.5 MP", abs(mpv() - 3.5) < 1e-6 and abs(w * h - 3.5e6) / 3.5e6 < 0.08, str((mpv(), w, h)))
pg.fill(".ndk-uimode .ndk-res-mp input", "500"); pg.keyboard.press("Enter"); pg.wait_for_timeout(400)
check("the value is limited by 100", mpv() == 100, str(mpv()))
pg.fill(".ndk-uimode .ndk-res-mp input", "abc"); pg.keyboard.press("Enter"); pg.wait_for_timeout(400)
check("garbage text is ignored", mpv() == 100 and J("document.querySelector('.ndk-uimode .ndk-res-mp input').value") == "100", str(mpv()))
check("the multiple is kept", all(v % 64 == 0 for v in size()), str(size()))
use({"mp": True, "mpValue": 1, "showFam": False})
check("works with the family chip switched off", vis(".ndk-res-mp"))
use({"mp": False, "mpValue": 2})
check("switching MP off brings the chip back and hides the field", not vis(".ndk-res-mp") and vis(".ndk-res-opts .ndk-chip"))
finish(p, br, errs)
