# ND UI bench 22: the side panels of the editor can be pulled wider (not narrower than the usual, not wider than a third of the window).
from lib import *
p, br, pg, errs = start(1500, 950)
J = lambda s, a=None: pg.evaluate(s, a) if a is not None else pg.evaluate(s)
setup(pg); build(pg)
J("window.ndUi.host().openEditor()"); pg.wait_for_timeout(1200)
cols = lambda: J("getComputedStyle(document.querySelector('.nde')).gridTemplateColumns").split(" ")
c = cols(); check("usual widths", c[0] == "304px" and c[2] == "332px", str(c))
hl = J("(()=>{const r=document.querySelector('.nde-split').getBoundingClientRect(); return [r.left+r.width/2, r.top+200]})()")
pg.mouse.move(*hl); pg.mouse.down(); pg.mouse.move(hl[0] + 120, hl[1], steps=5); pg.mouse.up(); pg.wait_for_timeout(200)
c = cols(); check("the left panel is 120 px wider", abs(float(c[0][:-2]) - 424) < 2, str(c))
pg.mouse.move(*[hl[0] + 120, hl[1]]); pg.mouse.down(); pg.mouse.move(1200, hl[1], steps=5); pg.mouse.up(); pg.wait_for_timeout(200)
c = cols(); check("not wider than a third of the window", float(c[0][:-2]) <= 500.5, str(c))
x = float(c[0][:-2])
pg.mouse.move(x, hl[1]); pg.mouse.down(); pg.mouse.move(20, hl[1], steps=5); pg.mouse.up(); pg.wait_for_timeout(200)
c = cols(); check("not narrower than the usual", float(c[0][:-2]) == 304, str(c))
hr = J("(()=>{const r=document.querySelectorAll('.nde-split')[1].getBoundingClientRect(); return [r.left+r.width/2, r.top+200]})()")
pg.mouse.move(*hr); pg.mouse.down(); pg.mouse.move(hr[0] - 150, hr[1], steps=5); pg.mouse.up(); pg.wait_for_timeout(200)
c = cols(); check("the right panel is 150 px wider", abs(float(c[2][:-2]) - 482) < 2, str(c))
check("the stage still fits (centre is what is left)", abs(float(c[1][:-2]) - (1500 - 304 - float(c[2][:-2]))) < 2, str(c))
# remembered
J("window.ndUi.host().editor?.close?.()"); pg.wait_for_timeout(500)
J("window.ndUi.host().openEditor()"); pg.wait_for_timeout(1200)
c = cols(); check("the width is remembered", abs(float(c[2][:-2]) - 482) < 2, str(c))
hr = J("(()=>{const r=document.querySelectorAll('.nde-split')[1].getBoundingClientRect(); return [r.left+r.width/2, r.top+200]})()")
pg.mouse.dblclick(*hr); pg.wait_for_timeout(200)
c = cols(); check("a double click gives back the usual width", c[2] == "332px", str(c))

# the tiles of the Widgets tab keep their size and more of them fit in a wider panel
J("document.querySelectorAll('.nde-tabs button')[1].click()"); pg.wait_for_timeout(400)
tiles = lambda: J("(()=>{const t=[...document.querySelectorAll('.nde-lib')[0].querySelectorAll('.nde-lib-i')]; return [Math.round(t[0].getBoundingClientRect().width), new Set(t.map(e=>Math.round(e.getBoundingClientRect().top))).size && t.filter(e=>Math.abs(e.getBoundingClientRect().top-t[0].getBoundingClientRect().top)<2).length]})()")
t0 = tiles(); check("tiles are 136 px, two in a row at the usual width", t0[0] == 136 and t0[1] == 2, str(t0))
hl = J("(()=>{const r=document.querySelector('.nde-split').getBoundingClientRect(); return [r.left+r.width/2, r.top+200]})()")
pg.mouse.move(*hl); pg.mouse.down(); pg.mouse.move(hl[0] + 190, hl[1], steps=5); pg.mouse.up(); pg.wait_for_timeout(300)
t1 = tiles(); check("a wider panel: the same tiles, more in a row", t1[0] == 136 and t1[1] >= 3, str(t1))
check("every tile has an icon", J("[...document.querySelectorAll('.nde-lib-i')].every(e=>e.querySelector('svg path,svg circle,svg rect'))") is True)
# labels and controls grow together
J("document.querySelectorAll('.nde-tabs button')[0].click()"); pg.wait_for_timeout(200)
lab = lambda: J("(()=>{const l=document.querySelector('.nde-right .nde-lab')||document.querySelector('.nde-lab'); return Math.round(l.getBoundingClientRect().width)})()")
l1 = lab(); hr = J("(()=>{const r=document.querySelectorAll('.nde-split')[1].getBoundingClientRect(); return [r.left+r.width/2, r.top+200]})()")
pg.mouse.dblclick(*hr); pg.wait_for_timeout(300); l_a = lab()
pg.mouse.move(*hr); pg.mouse.down(); pg.mouse.move(hr[0] - 150, hr[1], steps=5); pg.mouse.up(); pg.wait_for_timeout(300); l_b = lab()
check("labels of the inspector grow with the panel", l_b > l_a + 20, f"{l_a} -> {l_b}")
# up to the widest panel the label keeps its share of the row
pg.mouse.move(*hr); pg.mouse.down(); pg.mouse.move(hr[0] - 600, hr[1], steps=6); pg.mouse.up(); pg.wait_for_timeout(300)
sh = J("(()=>{const l=document.querySelector('.nde-sec-b .nde-row > .nde-lab'); const r=l.parentElement.getBoundingClientRect(); return [l.getBoundingClientRect().width, r.width]})()")
check("at the widest panel the label is still about half of the row", abs(sh[0] / sh[1] - 0.50) < 0.03, str(sh))
finish(p, br, errs)
